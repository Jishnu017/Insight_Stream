import httpx
from typing import List, Dict
from app.config import settings

GROQ_CHAT_URL = "https://api.groq.com/openai/v1/chat/completions"

async def generate_rag_response(context: str, user_message: str) -> str:
    if not settings.GROQ_API_KEY:
        raise ValueError("GROQ_API_KEY is not configured in settings.")

    headers = {
        "Authorization": f"Bearer {settings.GROQ_API_KEY}",
        "Content-Type": "application/json"
    }

    messages = [
        {"role": "system", "content": f"Answer using ONLY this context:\n\n{context}"},
        {"role": "user", "content": user_message}
    ]

    payload = {
        "messages": messages,
        "model": "qwen/qwen3.8-27b"
    }

    async with httpx.AsyncClient(timeout=30.0) as client:
        response = await client.post(GROQ_CHAT_URL, json=payload, headers=headers)
        response.raise_for_status()
        data = response.json()
        choices = data.get("choices", [])
        if choices and len(choices) > 0:
            return choices[0].get("message", {}).get("content", "")
        return "No response generated by LLM."
